export const HOUSE_BY_ID = new Map(HOUSE_CATALOG.map((house) => [house.id, house]));

export function isHouseId(value) {
  return typeof value === "string" && HOUSE_BY_ID.has(value);
}

export function getHouseById(id) {
  return HOUSE_BY_ID.get(id) || null;
}

export function sortHouseIdsByNumber(ids) {
  return [...new Set(ids)]
    .filter(isHouseId)
    .sort((left, right) => HOUSE_BY_ID.get(left).number - HOUSE_BY_ID.get(right).number);
}
